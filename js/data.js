/* 選項固定順序：直接照 data.js 裡的 選項 陣列（＝簡報上的 A、B 順序） */
window.取選項順序 = function (q) {
  return { 顯示選項: [q.選項[0], q.選項[1]], 顯示正解: q.正解 };
};

/* 全部 15 題攤平，供評量區使用 */
window.全部評量 = window.UNIT.重點.flatMap((r) =>
  r.評量.map((q, i) => ({ ...q, 重點: r.編號, 重點標題: r.標題, 序: i + 1 }))
);
